function attachCatalogImages(imagePool, products) {
  return products.map((product, index) => ({
    ...product,
    imageUrl: imagePool[index % imagePool.length],
    merchandisingRank: index + 1,
  }));
}

function buildCollection(config) {
  return {
    ...config,
    products: attachCatalogImages(config.imagePool, config.products),
  };
}

